#!/usr/bin/env node
/**
 * Generates server/src/arcade/core/lamplight/ranks169.ts, the committed strength order of the 169
 * starting-hand classes that Lamplight's bots use preflop (lamplight.md §13).
 *
 * The strength of a class is its average equity share against 2, 5 and 8 random hands
 * (equity × (opponents + 1), so a random hand scores 1 at every table size), by Monte Carlo with a
 * fixed seed per class. Averaging over table sizes ranks suited and connected hands the way they
 * play at a 6-handed table; heads-up alone would put 32o below 72o (72o is the weakest from about
 * five opponents on).
 *
 * Manual, never part of CI: `cd server && npx tsx scripts/gen-lamplight-ranks.mjs` (about 10–30 s
 * on 4 worker threads). Commit the file it writes; a test checks its recorded hash.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { register } from 'tsx/esm/api';

// Worker threads do not inherit the tsx loader: register it before loading the TypeScript core.
if (!isMainThread) register();
const { eval7 } = await import('../src/arcade/core/lamplight/evaluate.ts');
const { className } = await import('../src/arcade/core/lamplight/cards.ts');
const { fnv1a32 } = await import('../src/arcade/core/hash.ts');
const { utf8Encode } = await import('../src/arcade/core/bytes.ts');

const TABLE_SIZES = [2, 5, 8];
const TRIALS = 60_000;
const THREADS = 4;

/** A representative pair of cards for class `cls` (13 × 13 grid; suited above the diagonal). */
const cardsOf = (cls) => {
  const row = Math.floor(cls / 13);
  const col = cls % 13;
  if (row === col) return [row * 4, row * 4 + 1];
  if (row > col) return [row * 4 + 3, col * 4 + 3];
  return [col * 4 + 3, row * 4 + 2];
};

const strength = (cls) => {
  let s = (0x9e3779b9 ^ (cls * 0x85ebca6b)) >>> 0 || 1;
  const next = () => {
    s ^= s << 13;
    s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5;
    s >>>= 0;
    return s;
  };
  const hero = cardsOf(cls);
  const rest = [];
  for (let c = 0; c < 52; c++) if (c !== hero[0] && c !== hero[1]) rest.push(c);
  const cards = new Int32Array(7);
  const opp = new Int32Array(7);
  let total = 0;
  for (const k of TABLE_SIZES) {
    let share = 0;
    for (let t = 0; t < TRIALS; t++) {
      // Partial Fisher–Yates: the board (5) and 2k opponent cards from the front of `rest`.
      const need = 5 + 2 * k;
      for (let i = 0; i < need; i++) {
        const j = i + (next() % (rest.length - i));
        const tmp = rest[i];
        rest[i] = rest[j];
        rest[j] = tmp;
      }
      cards[0] = hero[0];
      cards[1] = hero[1];
      for (let i = 0; i < 5; i++) cards[2 + i] = rest[i];
      const mine = eval7(cards, 7);
      let best = true;
      let ties = 1;
      for (let o = 0; o < k && best; o++) {
        opp[0] = rest[5 + 2 * o];
        opp[1] = rest[6 + 2 * o];
        for (let i = 0; i < 5; i++) opp[2 + i] = rest[i];
        const v = eval7(opp, 7);
        if (v > mine) best = false;
        else if (v === mine) ties++;
      }
      if (best) share += 1 / ties;
    }
    total += (share / TRIALS) * (k + 1);
  }
  return total / TABLE_SIZES.length;
};

if (!isMainThread) {
  const out = [];
  for (const cls of workerData.classes) out.push([cls, strength(cls)]);
  parentPort.postMessage(out);
} else {
  const t0 = Date.now();
  const classes = Array.from({ length: 169 }, (_, i) => i);
  const parts = Array.from({ length: THREADS }, (_, w) => classes.filter((c) => c % THREADS === w));
  const results = (
    await Promise.all(
      parts.map(
        (part) =>
          new Promise((res, rej) => {
            const worker = new Worker(fileURLToPath(import.meta.url), { workerData: { classes: part } });
            worker.once('message', res);
            worker.once('error', rej);
          }),
      ),
    )
  ).flat();
  results.sort((a, b) => b[1] - a[1] || a[0] - b[0]);
  const order = results.map(([cls]) => className(cls)).join(' ');
  const scores = results.map(([, v]) => Math.round(v * 1000));
  const hash = fnv1a32(utf8Encode(order)) >>> 0;
  const file = `/**
 * The strength order of the 169 starting-hand classes, strongest first (lamplight.md §13).
 * Generated by server/scripts/gen-lamplight-ranks.mjs: the average equity share against 2, 5 and
 * 8 random hands, by seeded Monte Carlo. Do not edit by hand; a test checks RANKS169_HASH.
 */
export const RANKS169_ORDER =
  '${order}';

/** Strength × 1,000 of each entry of the order (1,000 = a random hand). */
export const RANKS169_SCORE: readonly number[] = [${scores.join(', ')}];

/** FNV-1a 32 of RANKS169_ORDER. */
export const RANKS169_HASH = 0x${hash.toString(16).padStart(8, '0')};
`;
  const target = resolve(dirname(fileURLToPath(import.meta.url)), '../src/arcade/core/lamplight/ranks169.ts');
  writeFileSync(target, file);
  console.log('wrote ' + target + ' in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
  console.log('first: ' + order.split(' ').slice(0, 8).join(' ') + ' … last: ' + order.split(' ').slice(-6).join(' '));
}
