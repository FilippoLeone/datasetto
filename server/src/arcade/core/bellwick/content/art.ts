/**
 * Bellwick: The Silent Bells, all pixel art (bellwick.md; baked by client/src/arcade/runtime/sprites.ts).
 * Each frame is h strings of w pixel chars: '.' is transparent, '0'-'9' and 'a'-'z' are palette indices 0-35.
 * The 'tiles' frame index is the tile code (content/legend.ts).
 *
 * Tiles are drawn once with semantic slots and every area palette recolours them:
 * 0 outline, 1 highlight, 2-5 ground (grass, stone floor, planks), 6-9 foliage and stone,
 * a-d wood and earth, e-h water and accent. Ground tiles sit on base colour 4, so objects match the floor.
 * Light comes from the top left everywhere. Tile 42 (under an NPC) is a woven mat that suits grass and planks.
 *
 * Hero slots: 0 outline, 1 white, 2-3 skin, 4 hair, 5-7 tunic (the only slots the four tunics change),
 * 8 boots and belt, 9-a metal, b-c leaf, d-e wood, f-g flame, h cream, i hair light, j blush, k boots light,
 * l eye white, m deep shadow, n spare.
 */

export interface ArtSheet {
  readonly id: string;
  readonly w: number;
  readonly h: number;
  readonly frames: readonly (readonly string[])[];
}

