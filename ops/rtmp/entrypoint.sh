#!/bin/sh
# Entrypoint of the rtmp image: enables RTMPS with Caddy's certificate, then runs nginx.
#
# The caddy_data volume is mounted read-only at /caddy. Caddy 2 keeps its certificates at
# /caddy/caddy/certificates/<issuer>/<host>/<host>.crt and .key, where <issuer> is
# acme-v02.api.letsencrypt.org-directory, acme.zerossl.com-v2-DV90 or local (internal CA).
# Those files are root-only, so this script starts as root just long enough to copy the
# newest pair for SITE_ADDRESS to /etc/nginx/certs for the nginx user and to write the
# RTMPS server block, then drops privileges; nginx itself never runs as root.
#
# Without a certificate (plain-HTTP setup, or Caddy still waiting for DNS) the server
# block stays empty: RTMPS is off and plain RTMP on 1935 works as before. A background
# loop repeats the check every RTMPS_CERT_CHECK_SECONDS (10 minutes) and reloads nginx
# when the certificate appears or is renewed, so Let's Encrypt renewals need no restart.
set -eu

CADDY_DATA="${CADDY_DATA:-/caddy}"
CERT_DIR=/etc/nginx/certs
RTMPS_CONF=/etc/nginx/rtmps/rtmps.conf
NGINX_PID=/opt/nginx/logs/nginx.pid
CHECK_INTERVAL="${RTMPS_CERT_CHECK_SECONDS:-600}"

log() { echo "entrypoint: $*" >&2; }

# "datasetto.example.com", "https://datasetto.example.com", "example.com:8443" -> host; ":80" -> "".
site_host() {
  h="${SITE_ADDRESS:-}"
  h="${h#*://}"
  h="${h%%/*}"
  h="${h%%:*}"
  printf '%s' "$h"
}

# Path of the newest certificate Caddy holds for the host (several issuers may have one).
newest_cert() {
  host="$1"
  [ -n "$host" ] && [ -d "$CADDY_DATA/caddy/certificates" ] || return 0
  find "$CADDY_DATA/caddy/certificates" -type f -path "*/$host/$host.crt" 2>/dev/null \
    | while IFS= read -r f; do printf '%s %s\n' "$(stat -c %Y "$f")" "$f"; done \
    | sort -rn | head -n 1 | cut -d' ' -f2-
}

# Copies the certificate pair and writes the RTMPS listener.
# Returns 0 when nginx must be reloaded (something changed), 1 when nothing changed.
sync_certs() {
  host="$(site_host)"
  crt="$(newest_cert "$host")"
  key="${crt%.crt}.key"
  if [ -z "$crt" ] || [ ! -s "$key" ]; then
    if [ -s "$RTMPS_CONF" ]; then
      log "certificate for '${host:-<none>}' is gone from $CADDY_DATA; RTMPS off"
      : > "$RTMPS_CONF"
      return 0
    fi
    return 1
  fi
  if [ -s "$RTMPS_CONF" ] && cmp -s "$crt" "$CERT_DIR/site.crt" && cmp -s "$key" "$CERT_DIR/site.key"; then
    return 1
  fi
  # Copy through temporary names so a reload never sees a half-written pair.
  cp "$crt" "$CERT_DIR/.site.crt" && cp "$key" "$CERT_DIR/.site.key"
  chown nginx:nginx "$CERT_DIR/.site.crt" "$CERT_DIR/.site.key"
  chmod 0600 "$CERT_DIR/.site.crt" "$CERT_DIR/.site.key"
  mv -f "$CERT_DIR/.site.crt" "$CERT_DIR/site.crt"
  mv -f "$CERT_DIR/.site.key" "$CERT_DIR/site.key"
  cat > "$RTMPS_CONF.tmp" <<'EOF'
# Generated by entrypoint.sh: RTMPS front for the rtmp server (see nginx.conf).
server {
    listen 1936 ssl;
    ssl_certificate /etc/nginx/certs/site.crt;
    ssl_certificate_key /etc/nginx/certs/site.key;
    proxy_protocol on;
    proxy_pass 127.0.0.1:1945;
}
EOF
  mv -f "$RTMPS_CONF.tmp" "$RTMPS_CONF"
  log "RTMPS on 1936 with certificate $crt"
  return 0
}

mkdir -p "$CERT_DIR" "$(dirname "$RTMPS_CONF")"
[ -e "$RTMPS_CONF" ] || : > "$RTMPS_CONF"
if ! sync_certs && [ ! -s "$RTMPS_CONF" ]; then
  log "no certificate for '$(site_host)' in $CADDY_DATA yet: plain RTMP on 1935 only, RTMPS starts once Caddy has one"
fi

# Docker created the log pipes for root, and nginx reopens /dev/stdout and /dev/stderr by
# path once it runs as the nginx user, so hand the pipes over first. No redirection on
# this line: busybox runs chown inside the shell itself, so "2>/dev/null" would point fd 2
# at /dev/null for the duration and the pipe would stay root-owned.
chown nginx /proc/$$/fd/1 /proc/$$/fd/2 || log "could not hand the log pipes to the nginx user; nginx may fail to open /dev/stderr"

# nginx becomes PID 1 (docker stop reaches it directly); the checker dies with the container.
(
  while sleep "$CHECK_INTERVAL"; do
    if sync_certs; then
      if [ -s "$NGINX_PID" ] && kill -HUP "$(cat "$NGINX_PID")" 2>/dev/null; then
        log "nginx reloaded"
      else
        log "could not signal nginx to reload"
      fi
    fi
  done
) &

exec su-exec nginx "$@"
